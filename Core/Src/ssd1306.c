static void SSD1306_WriteCommand(uint8_t cmd)
{
    if (SSD1306_I2C != NULL) {
        HAL_I2C_Mem_Write(SSD1306_I2C, SSD1306_I2C_ADDR, 0x00, 1, &cmd, 1, 10);
    }
}

SSD1306_Status SSD1306_Init(I2C_HandleTypeDef *hi2c)
{
    SSD1306_I2C = hi2c;
    SSD1306_Initialized = 0;

    /* Check if display is ready on I2C bus */
    if (HAL_I2C_IsDeviceReady(SSD1306_I2C, SSD1306_I2C_ADDR, 3, 50) != HAL_OK) {
        return SSD1306_ERR;
    }

    /* Initialization sequence for 128x64 OLED */
    HAL_Delay(10);
    SSD1306_WriteCommand(0xAE); // Display OFF
    SSD1306_WriteCommand(0x20); // Set Memory Addressing Mode
    SSD1306_WriteCommand(0x02); // Page Addressing Mode (0x02) - robust for direct page updates
    SSD1306_WriteCommand(0xB0); // Set Page Start Address for Page Addressing Mode, 0-7
    SSD1306_WriteCommand(0xC8); // Set COM Output Scan Direction
    SSD1306_WriteCommand(0x00); // Set low column address
    SSD1306_WriteCommand(0x10); // Set high column address
    SSD1306_WriteCommand(0x40); // Set start line address
    SSD1306_WriteCommand(0x81); // Set contrast control register
    SSD1306_WriteCommand(0x7F);
    SSD1306_WriteCommand(0xA1); // Set segment re-map 0 to 127
    SSD1306_WriteCommand(0xA6); // Set normal display
    SSD1306_WriteCommand(0xA8); // Set multiplex ratio(1 to 64)
    SSD1306_WriteCommand(0x3F); // 64 MUX
    SSD1306_WriteCommand(0xA4); // Output follows RAM content
    SSD1306_WriteCommand(0xD3); // Set display offset
    SSD1306_WriteCommand(0x00); // No offset
    SSD1306_WriteCommand(0xD5); // Set display clock divide ratio/oscillator frequency
    SSD1306_WriteCommand(0x80); // Set divide ratio
    SSD1306_WriteCommand(0xD9); // Set pre-charge period
    SSD1306_WriteCommand(0xF1);
    SSD1306_WriteCommand(0xDA); // Set com pins hardware configuration
    SSD1306_WriteCommand(0x12);
    SSD1306_WriteCommand(0xDB); // Set vcomh
    SSD1306_WriteCommand(0x40);
    SSD1306_WriteCommand(0x8D); // Set DC-DC enable
    SSD1306_WriteCommand(0x14); // Enable charge pump
    SSD1306_WriteCommand(0xAF); // Display ON

    SSD1306_Clear();
    if (SSD1306_UpdateScreen() != SSD1306_OK) {
        return SSD1306_ERR;
    }

    SSD1306_Initialized = 1;
    return SSD1306_OK;
}

void SSD1306_Fill(SSD1306_COLOR color)
{
    memset(SSD1306_Buffer, (color == SSD1306_COLOR_WHITE) ? 0xFF : 0x00, sizeof(SSD1306_Buffer));
}

void SSD1306_Clear(void)
{
    SSD1306_Fill(SSD1306_COLOR_BLACK);
}

SSD1306_Status SSD1306_UpdateScreen(void)
{
    if (SSD1306_I2C == NULL) {
        return SSD1306_ERR;
    }

    for (uint8_t page = 0; page < 8; page++) {
        SSD1306_WriteCommand(0xB0 + page);
        SSD1306_WriteCommand(0x00);
        SSD1306_WriteCommand(0x10);

        HAL_StatusTypeDef status = HAL_I2C_Mem_Write(
            SSD1306_I2C,
            SSD1306_I2C_ADDR,
            0x40,
            1,
            &SSD1306_Buffer[SSD1306_WIDTH * page],
            SSD1306_WIDTH,
            100
        );

        if (status != HAL_OK) {
            return SSD1306_ERR;
        }
    }
    return SSD1306_OK;
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, SSD1306_COLOR color)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) {
        return;
    }

    if (color == SSD1306_COLOR_WHITE) {
        SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] |= (1 << (y % 8));
    } else {
        SSD1306_Buffer[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
    }
}

void SSD1306_SetCursor(uint8_t x, uint8_t y)
{
    SSD1306_CurrentX = (x < SSD1306_WIDTH) ? x : (SSD1306_WIDTH - 1);
    SSD1306_CurrentY = (y < SSD1306_HEIGHT) ? y : (SSD1306_HEIGHT - 1);
}

char SSD1306_WriteChar(char ch, const SSD1306_Font_t *font, SSD1306_COLOR color)
{
    if (font == NULL) return 0;
    if (ch < 32 || ch > 126) ch = ' ';

    if (SSD1306_WIDTH < (SSD1306_CurrentX + font->width) ||
        SSD1306_HEIGHT < (SSD1306_CurrentY + font->height)) {
        return 0;
    }

    uint32_t charIndex = (uint32_t)(ch - 32);

    for (uint8_t row = 0; row < font->height; row++) {
        uint16_t rowData;
        if (font->is16bit) {
            const uint16_t *f16 = (const uint16_t *)font->data;
            rowData = f16[charIndex * font->height + row];
            for (uint8_t col = 0; col < font->width; col++) {
                if ((rowData >> (15 - col)) & 0x01) {
                    SSD1306_DrawPixel(SSD1306_CurrentX + col, SSD1306_CurrentY + row, color);
                } else {
                    SSD1306_DrawPixel(SSD1306_CurrentX + col, SSD1306_CurrentY + row,
                                      (color == SSD1306_COLOR_WHITE) ? SSD1306_COLOR_BLACK : SSD1306_COLOR_WHITE);
                }
            }
        } else {
            const uint8_t *f8 = (const uint8_t *)font->data;
            rowData = f8[charIndex * font->height + row];
            for (uint8_t col = 0; col < font->width; col++) {
                if ((rowData >> (7 - col)) & 0x01) {
                    SSD1306_DrawPixel(SSD1306_CurrentX + col, SSD1306_CurrentY + row, color);
                } else {
                    SSD1306_DrawPixel(SSD1306_CurrentX + col, SSD1306_CurrentY + row,
                                      (color == SSD1306_COLOR_WHITE) ? SSD1306_COLOR_BLACK : SSD1306_COLOR_WHITE);
                }
            }
        }
    }

    SSD1306_CurrentX += font->width;
    return ch;
}

char SSD1306_WriteString(const char *str, const SSD1306_Font_t *font, SSD1306_COLOR color)
{
    if (str == NULL || font == NULL) return 0;
    while (*str) {
        if (SSD1306_WriteChar(*str, font, color) != *str) {
            return *str;
        }
        str++;
    }
    return *str;
}

void SSD1306_PrintCentered(uint8_t y, const char *str, const SSD1306_Font_t *font, SSD1306_COLOR color)
{
    if (str == NULL || font == NULL) return;
    uint8_t len = (uint8_t)strlen(str);
    uint16_t totalWidth = len * font->width;
    uint8_t x = 0;
    if (totalWidth < SSD1306_WIDTH) {
        x = (SSD1306_WIDTH - totalWidth) / 2;
    }
    SSD1306_SetCursor(x, y);
    SSD1306_WriteString(str, font, color);
}

void SSD1306_DrawLine(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, SSD1306_COLOR color)
{
    int32_t dx = abs((int)x2 - (int)x1);
    int32_t sx = (x1 < x2) ? 1 : -1;
    int32_t dy = -abs((int)y2 - (int)y1);
    int32_t sy = (y1 < y2) ? 1 : -1;
    int32_t err = dx + dy, e2;

    while (1) {
        SSD1306_DrawPixel(x1, y1, color);
        if (x1 == x2 && y1 == y2) break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x1 += sx; }
        if (e2 <= dx) { err += dx; y1 += sy; }
    }
}
